export function isSupportedContactDialCode(value: unknown): value is string {
  return typeof value === "string" && contactPhoneCountries.some(country => country.dialCode === value);
}

export function contactNumberToE164(dialCode: string, phone: string) {
  if (!isSupportedContactDialCode(dialCode)) throw new Error("Enter a valid phone number with its country code.");
  const trimmed = phone.trim();
  if (!/^\+?[0-9 ().-]+$/.test(trimmed)) throw new Error("Enter a valid phone number with its country code.");
  let national = trimmed.replace(/\D/g, "");
  const international = trimmed.startsWith("+") || trimmed.startsWith("00");
  if (trimmed.startsWith("00")) national = national.slice(2);
  if (international && !national.startsWith(dialCode)) {
    throw new Error("Enter a valid phone number with its country code.");
  }
  if (international) {
    national = national.slice(dialCode.length);
  }
  national = national.replace(/^0+/, "");
  const digits = `${dialCode}${national}`;
  if (national.length < 6 || digits.length < 8 || digits.length > 15) {
    throw new Error("Enter a valid phone number with its country code.");
  }
  return `+${digits}`;
}
