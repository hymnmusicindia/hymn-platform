import assert from "node:assert/strict";
import { walletIncomeBalances, INCOME_MINIMUM_INR } from "../lib/income-policy";
const ledger=[{type:"studio_service_credit",amount:4000,direction:"credit"},{type:"beat_sale_credit",amount:6000,direction:"credit"},{type:"beat_sale_reversal",amount:1000,direction:"debit"},{type:"manual_adjustment",amount:500,direction:"credit"}];
let result=walletIncomeBalances(19500,19500,ledger,[]);
assert.deepEqual(result.totals,{artist_royalty:10000,studio:4000,producer_beat_sales:5000,other:500});
assert.equal(result.spendable.studio,4000,"Royalty funds cannot increase studio availability");
result=walletIncomeBalances(19500,15500,ledger,[{sourceType:"studio",amount:4000,status:"REQUESTED"}]);
assert.equal(result.spendable.studio,0,"A reservation cannot be withdrawn twice");
assert.equal(result.spendable.artist_royalty,10000);
result=walletIncomeBalances(19500,19500,ledger,[{sourceType:"studio",amount:4000,status:"REJECTED"}]);
assert.equal(result.spendable.studio,4000,"Rejected reservations restore source availability");
result=walletIncomeBalances(19500,10000,ledger,[{sourceType:"mixed",amount:9500,status:"PAID"}]);
assert.equal(result.unresolved,true,"Legacy mixed payouts require reconciliation, not guessed attribution");
assert.ok(Object.values(result.spendable).every(value=>value===0));
result=walletIncomeBalances(19500,3000,ledger,[]);
assert.ok(Object.values(result.spendable).every(value=>value<=3000),"Source availability is capped by the wallet");
assert.equal(INCOME_MINIMUM_INR.referral,1500);
assert.equal(INCOME_MINIMUM_INR.studio,3000);
console.log("Income source segregation, reversals, reservations, rejection release and legacy reconciliation verified.");
