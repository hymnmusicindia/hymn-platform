import assert from "node:assert/strict";
import { prisma } from "../lib/prisma";
import { refreshSpotifyArtistPhoto } from "../lib/spotify-artist-photos";
import { GET as cron } from "../app/api/cron/spotify-artist-photos/route";

process.env.SPOTIFY_CLIENT_ID = "fixture";
process.env.SPOTIFY_CLIENT_SECRET = "fixture";
process.env.CRON_SECRET = "fixture-cron";
const id = "12JfV940pzZKbQ24twPa8y";
let card: any = { id: 1, archivedAt: null, spotifyArtistId: id, spotifyProfileUrl: `https://open.spotify.com/artist/${id}`, imageUrl: "data:image/svg+xml;base64,placeholder" };
let photo: string | null = "https://i.scdn.co/image/first";
let status = 200;
let concurrentEdit = false;
let calls = 0;
let writes = 0;
let logs = 0;
const db = prisma as any;
db.artistCard.findUnique = async () => structuredClone(card);
db.artistCard.findMany = async () => [{ id: 1 }];
db.artistCard.updateMany = async ({ where, data }: any) => {
  if (where.spotifyProfileUrl !== card.spotifyProfileUrl || where.imageUrl !== card.imageUrl || card.archivedAt) return { count: 0 };
  Object.assign(card, data); writes++; return { count: 1 };
};
db.auditLog.create = async () => { logs++; return {}; };
db.$queryRaw = async (_query: any, ...values: any[]) => [{ run_id: values[1] }];
db.$executeRaw = async () => 1;
const originalFetch = globalThis.fetch;
globalThis.fetch = async (url) => {
  if (String(url).includes("api/token")) return new Response(JSON.stringify({ access_token: "fixture-token", expires_in: 3600 }), { status: 200 });
  calls++;
  if (concurrentEdit) card.spotifyProfileUrl = "https://open.spotify.com/artist/changed";
  return new Response(JSON.stringify({ id, name: "Fixture artist", images: photo ? [{ url: photo }] : [] }), { status });
};
async function main() {
  assert.equal((await cron(new Request("https://hymn.local/api/cron/spotify-artist-photos"))).status, 401);
  assert.equal(calls, 0, "Unauthorized CRON must not contact Spotify");
  assert.equal((await refreshSpotifyArtistPhoto(1)).outcome, "updated");
  assert.equal(card.imageUrl, photo);
  photo = "https://i.scdn.co/image/updated";
  await refreshSpotifyArtistPhoto(1);
  assert.equal(card.imageUrl, photo, "Refresh bypasses the artist cache");
  photo = null;
  await refreshSpotifyArtistPhoto(1);
  assert.equal(card.imageUrl, "https://i.scdn.co/image/updated", "Missing image preserves last good photo");
  status = 429;
  await assert.rejects(() => refreshSpotifyArtistPhoto(1), /429/);
  assert.equal(card.imageUrl, "https://i.scdn.co/image/updated");
  status = 200;
  photo = "https://i.scdn.co/image/next";
  concurrentEdit = true;
  assert.equal((await refreshSpotifyArtistPhoto(1)).outcome, "superseded");
  assert.equal(card.imageUrl, "https://i.scdn.co/image/updated", "Concurrent profile edits must win");
  concurrentEdit = false;
  card.spotifyProfileUrl = `https://open.spotify.com/artist/${id}`;
  card.spotifyArtistId = "wrong";
  const before = calls;
  await assert.rejects(() => refreshSpotifyArtistPhoto(1), /do not match/);
  assert.equal(calls, before, "Mismatched identity must not fetch a different artist");
  card.spotifyArtistId = id;
  const response = await cron(new Request("https://hymn.local/api/cron/spotify-artist-photos", { headers: { authorization: "Bearer fixture-cron" } }));
  assert.equal(response.status, 200);
  assert.equal((await response.json()).updated, 1);
  assert.equal(logs, 1);
  card.archivedAt = new Date();
  const previousWrites = writes;
  assert.equal((await refreshSpotifyArtistPhoto(1)).outcome, "skipped");
  assert.equal(writes, previousWrites);
  console.log("Spotify artist photo refresh: updated images, daily CRON, authentication, identity safety, concurrency, missing images and provider failure checks passed.");
}
main().catch(error => { console.error(error); process.exitCode = 1; }).finally(() => { globalThis.fetch = originalFetch; });
