import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { prisma } from '../lib/prisma';
import { teamMutation, teamRead } from '../lib/team/service';
async function main() {
  assert.equal(process.env.DATABASE_URL, 'postgresql://fixture:fixture@127.0.0.1:55473/acquisition_fixture');
  const ws = await prisma.teamWorkspace.create({ data: { name: 'Chat fixture' } });
  async function member(name: string, workspaceId = ws.id, permissions = ['chat.use']) {
    const role = await prisma.teamRole.create({ data: { workspaceId, name: name + randomUUID(), permissions } });
    const user = await prisma.user.create({ data: { name, googleId: randomUUID(), email: randomUUID() + '@chat.fixture.invalid', avatar: 'https://lh3.googleusercontent.com/test' } });
    return prisma.teamMember.create({ data: { workspaceId, userId: user.id, roleId: role.id }, include: { role: true } });
  }
  const a = await member('Amira'), b = await member('Ben'), c = await member('Cara'), viewer = await member('Viewer', ws.id, []);
  const foreign = await prisma.teamWorkspace.create({ data: { name: 'Other workspace' } });
  const outsider = await member('Outsider', foreign.id);
  const dm = await teamMutation(a, 'chat-direct', { memberId: b.id });
  assert.ok(dm.id.startsWith('dm-')); assert.equal(dm.private, true);
  assert.deepEqual([...dm.memberIds].sort(), [a.id, b.id].sort());
  assert.equal((await teamMutation(b, 'chat-direct', { memberId: a.id })).id, dm.id);
  await assert.rejects(teamMutation(a, 'chat-direct', { memberId: a.id }), /another/);
  await assert.rejects(teamMutation(a, 'chat-direct', { memberId: outsider.id }), /active members/);
  await assert.rejects(teamMutation(a, 'chat-direct', { memberId: viewer.id }), /active members/);
  const group = await teamMutation(a, 'chat-group', { name: 'Release team', memberIds: [b.id, c.id] });
  assert.ok(!group.id.startsWith('dm-')); assert.equal(group.memberIds.length, 3);
  const request = { channelId: dm.id, body: 'Hello Ben, ready for the release?', clientKey: randomUUID() };
  const [first, retry] = await Promise.all([teamMutation(a, 'chat-send', request), teamMutation(a, 'chat-send', request)]);
  assert.equal(first.id, retry.id);
  assert.equal(await prisma.teamMessage.count({ where: { channelId: dm.id } }), 1);
  assert.equal(await prisma.teamNotification.count({ where: { memberId: b.id } }), 1);
  await assert.rejects(teamMutation(a, 'chat-send', { ...request, body: 'Different content' }), /differs/);
  await assert.rejects(teamMutation(c, 'chat-send', { ...request, clientKey: randomUUID() }), /unavailable/);
  await assert.rejects(teamRead(c, 'messages', new URLSearchParams({ channel: dm.id })), /unavailable/);
  await assert.rejects(teamMutation(c, 'chat-read', { channelId: dm.id, ids: [first.id] }), /unavailable/);
  const before = await teamRead(b, 'chat-conversations', new URLSearchParams());
  assert.equal(before.items.find(i => i.id === dm.id)!.unread, 1);
  assert.equal(before.items.find(i => i.id === dm.id)!.name, 'Amira');
  assert.equal(before.items.find(i => i.id === dm.id)!.avatar, 'https://lh3.googleusercontent.com/test');
  assert.ok(!before.members.some(m => m.id === outsider.id || m.id === viewer.id));
  await teamMutation(b, 'chat-read', { channelId: dm.id, ids: [first.id] });
  await teamMutation(b, 'chat-read', { channelId: dm.id, ids: [first.id] });
  const detail = await teamRead(a, 'messages', new URLSearchParams({ channel: dm.id }));
  assert.deepEqual([...detail.items[0].readMemberIds].sort(), [a.id, b.id].sort());
  assert.ok(detail.readers.some(r => r.id === b.id && r.user.name === 'Ben'));
  assert.equal((await teamRead(b, 'chat-conversations', new URLSearchParams())).items.find(i => i.id === dm.id)!.unread, 0);
  const groupMessage = await teamMutation(a, 'chat-send', { channelId: group.id, body: 'Team, please review the schedule.', clientKey: randomUUID() });
  await teamMutation(b, 'chat-read', { channelId: group.id, ids: [groupMessage.id] });
  await teamMutation(c, 'chat-read', { channelId: group.id, ids: [groupMessage.id] });
  const seen = await teamRead(a, 'messages', new URLSearchParams({ channel: group.id }));
  assert.equal(seen.items[0].readMemberIds.length, 3);
  assert.ok(seen.readers.every(r => !!r.user.avatar));
  await teamMutation(b, 'chat-read', { channelId: group.id, ids: [first.id] });
  assert.equal(await prisma.teamMessage.count({ where: { channelId: dm.id } }), 1);
  assert.equal((await teamRead(outsider, 'chat-conversations', new URLSearchParams())).items.length, 0);
  await prisma.teamMessage.update({ where: { id: first.id }, data: { deletedAt: new Date() } });
  assert.equal((await teamRead(a, 'messages', new URLSearchParams({ channel: dm.id }))).items.length, 0);
  await prisma.teamMember.update({ where: { id: b.id }, data: { status: 'INACTIVE' } });
  await assert.rejects(teamMutation(b, 'chat-send', { ...request, clientKey: randomUUID() }), /revoked/);
  await assert.rejects(teamMutation(viewer, 'chat-group', { name: 'No permission', memberIds: [a.id] }), /permission/);
  console.log('PASS Team chat: private DMs, groups, cross-workspace isolation, concurrent send deduplication, notifications, scoped/idempotent reads, avatars, unread counts, deleted messages and revoked access.');
}
main().catch(e => { console.error(e); process.exitCode = 1; }).finally(() => prisma.$disconnect());
