import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { NextRequest } from 'next/server';
import { audioFileResponse } from '../lib/audio-file-response';
import { openPrivateAssetAudio } from '../lib/private-storage';
import { GET, HEAD } from '../app/api/public-uploads/[...path]/route';

async function main() {
  await fs.mkdir('.cache', { recursive: true });
  const root = await fs.mkdtemp(path.resolve('.cache/audio-streaming-'));
  await fs.mkdir(path.join(root, 'beats'));
  const filename = path.join(root, 'beats', 'preview.mp3');
  const size = 16 * 1024 * 1024;
  const writer = await fs.open(filename, 'w');
  await writer.truncate(size);
  await writer.write(Buffer.from('0123456789abcdef'), 0, 16, 0);
  await writer.write(Buffer.from('END'), 0, 3, size - 3);
  await writer.close();
  const respond = async (headers = {}, method = 'GET') => audioFileResponse(new Request('https://hymn.test/audio', { headers, method }), await fs.open(filename, 'r'), { mimeType: 'audio/mpeg', cacheControl: 'private, no-cache', etag: '"master-v1"' });
  const tiny = await respond({ Range: 'bytes=0-15' });
  assert.equal(tiny.status, 206);assert.equal(tiny.headers.get('Content-Length'), '16');
  assert.equal(tiny.headers.get('Content-Range'), `bytes 0-15/${size}`);assert.equal(await tiny.text(), '0123456789abcdef');
  const tail = await respond({ Range: 'bytes=-3' });assert.equal(await tail.text(), 'END');
  const seek = await respond({ Range: 'bytes=8-11' });assert.equal(await seek.text(), '89ab');
  for (const Range of ['bytes=999999999-', 'bytes=9-2', 'bytes=-0', 'bytes=0-1,8-9']) assert.equal((await respond({ Range })).status, 416);
  const head = await respond({}, 'HEAD');assert.equal(head.body, null);assert.equal(head.headers.get('Content-Length'), String(size));
  const cachedFile = await fs.open(filename, 'r');
  const cached = await audioFileResponse(new Request('https://hymn.test/audio', { headers: { 'If-None-Match': 'W/"master-v1"' } }), cachedFile, { mimeType: 'audio/mpeg', cacheControl: 'private, no-cache', etag: '"master-v1"' });
  assert.equal(cached.status, 304);assert.equal(cached.body, null);await assert.rejects(() => cachedFile.stat());
  const changed = await respond({ Range: 'bytes=0-1', 'If-Range': '"old-version"' });assert.equal(changed.status, 200);await changed.body!.cancel();
  const same = await respond({ Range: 'bytes=0-1', 'If-Range': '"master-v1"' });assert.equal(same.status, 206);await same.body!.cancel();
  const streamingFile = await fs.open(filename, 'r');
  const streamed = await audioFileResponse(new Request('https://hymn.test/audio'), streamingFile, { mimeType: 'audio/mpeg', cacheControl: 'private, no-cache' });
  const reader = streamed.body!.getReader();const first = await reader.read();
  assert.ok(first.value && first.value.length <= 64 * 1024, 'Playback begins with one bounded chunk, not the complete 16MB source');
  await reader.cancel();await new Promise(resolve => setTimeout(resolve, 30));await assert.rejects(() => streamingFile.stat());
  const abortedFile = await fs.open(filename, 'r');const controller = new AbortController();
  const aborted = await audioFileResponse(new Request('https://hymn.test/audio', { signal: controller.signal }), abortedFile, { mimeType: 'audio/mpeg', cacheControl: 'private, no-cache' });
  controller.abort();await assert.rejects(() => aborted.arrayBuffer());await new Promise(resolve => setTimeout(resolve, 30));await assert.rejects(() => abortedFile.stat());
  process.env.STORAGE_ROOT = root;process.env.HYMN_STORAGE_ROOT = root;
  const context = { params: Promise.resolve({ path: ['beats', 'preview.mp3'] }) };
  const publicRange = await GET(new NextRequest('https://hymn.test/api/public-uploads/beats/preview.mp3', { headers: { Range: 'bytes=0-1' } }), context);
  assert.equal(publicRange.status, 206);assert.equal(await publicRange.text(), '01');assert.match(publicRange.headers.get('Cache-Control')!, /immutable/);
  const publicHead = await HEAD(new NextRequest('https://hymn.test/api/public-uploads/beats/preview.mp3', { method: 'HEAD' }), context);assert.equal(publicHead.body, null);assert.equal(publicHead.headers.get('Content-Length'), String(size));
  const privateFile = await openPrivateAssetAudio({ objectKey: 'beats/preview.mp3', byteSize: size });await privateFile.close();
  await assert.rejects(() => openPrivateAssetAudio({ objectKey: 'beats/preview.mp3', byteSize: 1 }));
  await assert.rejects(() => openPrivateAssetAudio({ objectKey: '../preview.mp3', byteSize: size }));
  console.log('PASS progressive 64KB streaming from a 16MB source, Safari byte probes, seeking/suffixes, 416, HEAD, ETag/If-Range, cancellation, public route and private path/size checks');
}
main().catch(error => { console.error(error);process.exitCode = 1; });
