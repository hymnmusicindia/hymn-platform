import assert from "node:assert/strict";
import { spawn } from "node:child_process";
import { chromium, expect } from "@playwright/test";
import jwt from "jsonwebtoken";
import { prisma } from "../lib/prisma";

async function main() {
  assert.ok(process.env.DATABASE_URL?.includes("127.0.0.1:55461/team_fixture"));
  const member = await prisma.teamMember.findFirstOrThrow({ where: { workspace: { name: { startsWith: "Contact fixture" } }, role: { owner: true } }, include: { user: true } });
  const existing = await prisma.teamClient.findFirstOrThrow({ where: { workspaceId: member.workspaceId, name: "Existing Artist" } });
  const origin = "http://127.0.0.1:35469", secret = "team-client-browser-test-secret";
  const server = spawn(process.execPath, ["node_modules/next/dist/bin/next", "dev", "--webpack", "--port", "35469", "--hostname", "127.0.0.1"], { env: { ...process.env, JWT_SECRET: secret, NEXT_DIST_DIR: ".next-team-appointments-review", NEXT_PUBLIC_APP_URL: origin, EMAIL_ENABLED: "false" }, stdio: ["ignore", "pipe", "pipe"], windowsHide: true });
  const browser = await chromium.launch();
  try {
    await new Promise<void>((resolve, reject) => { const timer = setTimeout(() => reject(new Error("Calendar test server did not start")), 120000); server.stdout?.on("data", chunk => { if (/Ready in/.test(chunk.toString())) { clearTimeout(timer); resolve(); } }); server.stderr?.on("data", chunk => process.stderr.write(chunk)); server.on("exit", () => reject(new Error("Calendar test server exited"))); });
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
    await context.addCookies([{ name: "hymn_session", value: jwt.sign({ sub: member.userId, name: member.user.name, email: member.user.email, role: "customer" }, secret), url: origin }]);
    const page = await context.newPage(); page.setDefaultTimeout(120000);
    await page.goto(`${origin}/team?module=calendar&workspace=${member.workspaceId}`, { waitUntil: "load", timeout: 120000 });
    await page.getByRole("button", { name: "Schedule event", exact: true }).click();
    const dialog = page.locator("dialog[open]");
    await page.getByLabel("Event title").fill("Start-only browser appointment");
    await dialog.getByRole("button", { name: "+ Add client card here", exact: true }).click();
    await page.getByLabel("New client name", { exact: true }).fill("Inline browser client");
    await page.getByLabel("New client email", { exact: true }).fill(`inline-${member.id}@example.test`);
    const [createdResponse] = await Promise.all([page.waitForResponse(r => r.url().includes("/api/team/clients-save") && r.request().method() === "POST"), dialog.getByRole("button", { name: "Create & select client", exact: true }).click()]);
    assert.equal(createdResponse.status(), 200);
    await expect(dialog.locator('select[name="clientId"]')).not.toHaveValue("", { timeout: 120000 });
    await expect(page.getByLabel("Event title", { exact: true })).toHaveValue("Start-only browser appointment");
    await expect(dialog.getByRole("combobox", { name: "Type", exact: true })).toHaveValue("CALL");
    await expect(page.getByLabel("Start time hour", { exact: true })).toHaveValue("");
    await expect(page.getByLabel("End time hour", { exact: true })).toHaveValue("");
    await dialog.getByRole("button", { name: "Save", exact: true }).click();
    assert.equal(await prisma.teamCalendarEvent.count({ where: { title: "Start-only browser appointment" } }), 0);
    await page.getByLabel("Start time hour", { exact: true }).selectOption("12");
    await page.getByLabel("Start time minute", { exact: true }).selectOption("00");
    await page.getByLabel("Start time AM or PM", { exact: true }).selectOption("AM");
    await dialog.getByRole("button", { name: "Save", exact: true }).click();
    await expect(dialog).toHaveCount(0, { timeout: 120000 });
    const appointment = await prisma.teamCalendarEvent.findFirstOrThrow({ where: { title: "Start-only browser appointment" } });
    assert.equal(appointment.endsAt, null); assert.equal(appointment.startsAt.getUTCHours(), 18); assert.equal(appointment.startsAt.getUTCMinutes(), 30);
    await page.getByRole("button", { name: "New client card", exact: true }).click();
    await page.getByLabel("Primary email (optional)", { exact: true }).fill(existing.email);
    await expect(dialog.getByText("Existing HYMN account", { exact: false })).toBeVisible({ timeout: 120000 });
    await page.getByRole("button", { name: "Close calendar form" }).click();
    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByRole("button", { name: "Schedule event", exact: true }).click();
    await dialog.getByRole("button", { name: "Choose on clock" }).first().click();
    await page.getByRole("button", { name: "Start time hour 3", exact: true }).click();
    await page.getByRole("button", { name: "Start time minute 15", exact: true }).click();
    await expect(page.getByLabel("Start time hour", { exact: true })).toHaveValue("3");
    await expect(page.getByLabel("Start time minute", { exact: true })).toHaveValue("15");
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 2));
    await page.getByRole("button", { name: "Close calendar form" }).click();
    const date = new Date(Date.now() + 330 * 60000).toISOString().slice(0, 10);
    await page.getByRole("button", { name: /Start-only browser appointment/ }).first().click();
    await expect(dialog.getByRole("heading", { name: "Event details", exact: true })).toBeVisible();
    await expect(page.getByLabel("Schedule item type", { exact: true })).toHaveCount(0);
    await page.getByRole("button", { name: "Close calendar form" }).click();
    // Click the date/blank surface, not an overlaid event chip's centre.
    await page.getByRole("button", { name: `View schedule for ${date}`, exact: true }).click({ position: { x: 8, y: 8 } });
    const dayDialog = page.getByRole("dialog").filter({ has: page.locator("#calendar-day-title") });
    await expect(dayDialog.getByRole("heading", { name: "Start-only browser appointment", exact: true })).toBeVisible();
    await dayDialog.getByRole("button", { name: "Delete event", exact: true }).first().click();
    await dayDialog.getByRole("button", { name: "Keep event", exact: true }).click();
    await expect(dayDialog.getByRole("heading", { name: "Start-only browser appointment", exact: true })).toBeVisible();
    const target = dayDialog.locator("article").filter({ has: page.getByRole("heading", { name: "Start-only browser appointment", exact: true }) });
    await target.getByRole("button", { name: "Delete event", exact: true }).click();
    await target.getByRole("button", { name: "Confirm delete", exact: true }).click();
    await expect(dayDialog.getByRole("heading", { name: "Start-only browser appointment", exact: true })).toHaveCount(0);
    assert.equal((await prisma.teamCalendarEvent.findUniqueOrThrow({ where: { id: appointment.id } })).status, "DELETED");
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 2));
    await dayDialog.getByRole("button", { name: "+ Schedule on this day", exact: true }).click();
    await page.getByLabel("Schedule item type", { exact: true }).selectOption("TASK");
    await page.getByLabel("Task title", { exact: true }).fill("Calendar browser My Work task");
    await page.getByLabel("Start time hour", { exact: true }).selectOption("4");
    await page.getByLabel("Start time minute", { exact: true }).selectOption("15");
    await page.getByLabel("Start time AM or PM", { exact: true }).selectOption("PM");
    await dialog.getByRole("button", { name: "Save", exact: true }).click();
    await expect(dialog).toHaveCount(0, { timeout: 120000 });
    const task = await prisma.teamTask.findFirstOrThrow({ where: { workspaceId: member.workspaceId, title: "Calendar browser My Work task" } });
    await expect(page.locator(`a[href*="task=${task.id}"]`).first()).toBeVisible();
    await page.getByLabel("Filter calendar type", { exact: true }).selectOption("CALL");
    await expect(page.locator(`a[href*="task=${task.id}"]`)).toHaveCount(0);
    await page.getByLabel("Filter calendar type", { exact: true }).selectOption("TASK");
    await page.locator(`a[href*="task=${task.id}"]`).first().click();
    await expect(page.getByRole("dialog").getByRole("heading", { name: "Calendar browser My Work task", exact: true })).toBeVisible();
    console.log("PASS: day-cell quick scheduling, task creation, type filters, My Work deep link and mobile interaction.");
    console.log("PASS: inline client creation selects the card, defaults to CALL and preserves appointment form fields.");
    console.log("PASS: day detail popup, mobile layout, cancel-delete, inline confirmed deletion and schedule-from-day flow.");
    console.log("PASS: blank AM/PM controls, required-start browser validation, start-only save/midnight conversion, account matching and mobile dial layout.");
  } finally {
    await browser.close();
    if (server.pid && process.platform === "win32") await new Promise<void>(resolve => { const child = spawn("taskkill", ["/PID", String(server.pid), "/T", "/F"], { stdio: "ignore", windowsHide: true }); child.on("exit", () => resolve()); }); else server.kill();
  }
}
main().catch(error => { console.error(error); process.exitCode = 1; }).finally(() => prisma.$disconnect());
